const displayNames = new Map<string, Intl.DisplayNames>();
function regionName(iso2: string, locale: Locale) {
  if (!iso2) return null;
  let dn = displayNames.get(locale);
  if (!dn) {
    try {
      dn = new Intl.DisplayNames([locale], { type: "region" });
      displayNames.set(locale, dn);
    } catch {
      return null;
    }
  }
  try {
    return dn.of(iso2) ?? null;
  } catch {
    return null;
  }
}

const BY_CODE = new Map(RAW.map(([c, iso2, name]) => [c, { iso2, name }]));

/** Country name in the viewer's language (falls back to the English name, then the code). */
export function countryName(code: string | null | undefined, locale: Locale = "en") {
  if (!code) return "";
  const c = BY_CODE.get(code);
  if (!c) return code;
  return (locale !== "en" && regionName(c.iso2, locale)) || c.name;
}

/** [code, localized name] sorted alphabetically for the given language. */
export function countryList(locale: Locale = "en"): [string, string][] {
  return RAW.map(([c]) => [c, countryName(c, locale)] as [string, string]).sort((a, b) =>
    a[1].localeCompare(b[1], locale),
  );
}
