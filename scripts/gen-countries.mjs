// Regenerates src/lib/countries.ts with English + Mongolian names.
// Mongolian names come from Node's full ICU (CLDR) and are stored as data, because Chrome ships
// without Mongolian locale data — Intl.DisplayNames("mn") falls back to English in the browser.
// Usage: node scripts/gen-countries.mjs
import { readFileSync, writeFileSync } from "node:fs";

const FILE = "src/lib/countries.ts";
const src = readFileSync(FILE, "utf8");

// Accept either the old [iso3, iso2, en] rows or the current [iso3, en, mn] rows
const old = [...src.matchAll(/\["([A-Z]{3})", "([A-Z]{0,2}(?:-[A-Z]{2})?)", ("(?:[^"\\]|\\.)*")\]/g)];
if (old.length === 0) {
  console.log("countries.ts already contains Mongolian names — nothing to do.");
  process.exit(0);
}

const FIXES = { CYN: "Хойд Кипр", SOL: "Сомалиланд" }; // not in CLDR
const ISO2_FIX = { "CN-TW": "TW" };
const dn = new Intl.DisplayNames(["mn"], { type: "region" });

const rows = old.map((m) => {
  const iso3 = m[1];
  const iso2 = ISO2_FIX[m[2]] ?? m[2];
  const en = JSON.parse(m[3]);
  let mn = FIXES[iso3] ?? en;
  if (!FIXES[iso3] && iso2) {
    const v = dn.of(iso2);
    if (v && v !== iso2) mn = v;
  }
  return [iso3, en, mn];
});

const lines = rows.map((r) => `  [${r.map((x) => JSON.stringify(x)).join(", ")}]`).join(",\n");
writeFileSync(
  FILE,
  `import type { Locale } from "@/i18n/config";

// ISO 3166-1 alpha-3 code, English name (Natural Earth, public domain) and Mongolian name (CLDR).
// Generated by scripts/gen-countries.mjs — Mongolian names are stored here because Chrome ships
// without Mongolian locale data, so Intl.DisplayNames("mn") falls back to English in the browser.
const RAW: [iso3: string, en: string, mn: string][] = [
${lines},
];

const BY_CODE = new Map(RAW.map(([c, en, mn]) => [c, { en, mn }]));

/** Country name in the viewer's language (falls back to the code for unknown countries). */
export function countryName(code: string | null | undefined, locale: Locale = "en") {
  if (!code) return "";
  const c = BY_CODE.get(code);
  if (!c) return code;
  return locale === "mn" ? c.mn : c.en;
}

/** [code, localized name] sorted alphabetically for the given language. */
export function countryList(locale: Locale = "en"): [string, string][] {
  return RAW.map(([c]) => [c, countryName(c, locale)] as [string, string]).sort((a, b) =>
    a[1].localeCompare(b[1], locale),
  );
}
`,
);
console.log(`Wrote ${rows.length} countries.`);
